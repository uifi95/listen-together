#!/bin/bash
# Builds ListenTogether.app into ./build.
set -euo pipefail
cd "$(dirname "$0")"

# Embed the JavaScript bridges as Swift string literals.
gen=Sources/ListenTogether/EmbeddedJS.swift
{
  echo "// Generated by build.sh from js/. Do not edit."
  echo "enum EmbeddedJS {"
  for pair in "qobuzHost:js/qobuz-host.js" "qobuzPage:js/qobuz-page.js" "apple:js/apple.js"; do
    name=${pair%%:*}; file=${pair#*:}
    if grep -q '"####' "$file"; then echo "error: $file contains a raw-string delimiter" >&2; exit 1; fi
    printf '    static let %s = ####"""\n' "$name"
    cat "$file"
    printf '"""####\n'
  done
  echo "    static let appleVersion = $(sed -nE 's/.*const VERSION = ([0-9]+);.*/\1/p' js/apple.js | head -1)"
  echo "}"
} > "$gen"

# Universal: runs on Apple Silicon and Intel Macs.
arch=(--arch arm64 --arch x86_64)
swift build -c release "${arch[@]}" --product ListenTogether

# OUT=dir ./build.sh builds somewhere else (e.g. while the app in build/ is running).
out=${OUT:-build}
app=$out/ListenTogether.app
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$(swift build -c release "${arch[@]}" --show-bin-path)/ListenTogether" "$app/Contents/MacOS/"
[ -f AppIcon.icns ] && cp AppIcon.icns "$app/Contents/Resources/"

cat > "$app/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>ListenTogether</string>
  <key>CFBundleDisplayName</key><string>ListenTogether</string>
  <key>CFBundleIdentifier</key><string>app.listentogether.mac</string>
  <key>CFBundleExecutable</key><string>ListenTogether</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.music</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSPrincipalClass</key><string>NSApplication</string>
  <key>CFBundleURLTypes</key>
  <array>
    <dict>
      <key>CFBundleURLName</key><string>ListenTogether invite</string>
      <key>CFBundleURLSchemes</key><array><string>listentogether</string></array>
    </dict>
  </array>
</dict>
</plist>
PLIST

codesign --force --sign - "$app"
echo "Built $app"

# Zip to share (ditto keeps the bundle's signature and attributes intact).
rm -f "$out/ListenTogether.zip"
ditto -c -k --keepParent "$app" "$out/ListenTogether.zip"
echo "Packed $out/ListenTogether.zip"
